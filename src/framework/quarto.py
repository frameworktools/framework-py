"""Generating ``_quarto.yml`` files for a project, as the R package does."""

from __future__ import annotations

import posixpath
import re
from collections import Counter
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path
from typing import Any

from framework._log import inform
from framework.errors import FrameworkError
from framework.settings import settings_read

_HTML_DEFAULTS: dict[str, Any] = {
    "theme": "default",
    "toc": True,
    "toc_depth": 3,
    "code_fold": False,
    "code_tools": False,
    "embed_resources": True,
    "highlight_style": "github",
}
_REVEALJS_DEFAULTS: dict[str, Any] = {
    "theme": "default",
    "incremental": False,
    "slide_number": True,
    "transition": "slide",
    "background_transition": "fade",
    "controls": True,
    "progress": True,
    "center": True,
    "highlight_style": "github",
}


def _value(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    return str(value)


def quarto_yml(
    settings: dict[str, Any] | None,
    format: str = "html",
    project_root: bool = False,
    output_dir: str | None = None,
) -> str:
    """The text of one ``_quarto.yml`` file."""
    if format not in ("html", "revealjs"):
        raise FrameworkError("Format must be 'html' or 'revealjs'")
    defaults = _HTML_DEFAULTS if format == "html" else _REVEALJS_DEFAULTS
    given = (settings or {}).get(format)
    options = {**defaults, **(given if isinstance(given, dict) else {})}

    lines = [
        f"# Auto-generated by Framework on {date.today():%Y-%m-%d}",
        "# This file is yours to customize - Framework will not modify it after creation",
        "# framework.quarto_regenerate() adds missing keys only; overwrite=True replaces it",
        "",
    ]
    if project_root or output_dir:
        lines.append("project:")
        if project_root:
            lines.append("  type: default")
        if output_dir:
            lines.append(f"  output-dir: {output_dir}")
        lines.append("")
    lines.append("format:")
    lines.append(f"  {format}:")
    for key in defaults:
        if key == "format":
            continue
        lines.append(f"    {key.replace('_', '-')}: {_value(options[key])}")
    return "\n".join(lines) + "\n"


def render_format(dir_key: str, project_type: str | None = None) -> str:
    """Slides render as revealjs, everything else as HTML."""
    if re.search(r"slides?", dir_key, re.IGNORECASE):
        return "revealjs"
    if project_type == "presentation" and dir_key == "root":
        return "revealjs"
    return "html"


def _shared_output_dir(pairs: list[tuple[str, str, str, str | None]]) -> str | None:
    """The parent most render targets share, as R picks it. None means in place."""
    counts = Counter(parent for *_, parent in pairs if parent is not None)
    if not counts:
        return None
    # Ties go to the parent that sorts first, as in R
    best = min(counts, key=lambda parent: (-counts[parent], parent))
    return None if best == "." else best


def _render_pairs(
    render_dirs: dict[str, str] | None, directories: dict[str, str] | None
) -> list[tuple[str, str, str, str | None]]:
    """Render folders as (key, source, target, parent): the parent is "." when the target is
    the source itself, None when the target doesn't end in the source."""
    pairs: list[tuple[str, str, str, str | None]] = []
    for key, target in (render_dirs or {}).items():
        source = (directories or {}).get(key, key)
        if not isinstance(target, str) or not isinstance(source, str) or not target or not source:
            continue
        if target == source:
            parent: str | None = "."
        elif target.endswith(f"/{source}"):
            parent = target[: -len(source) - 1]
        else:
            parent = None
        pairs.append((key, source, target, parent))
    return pairs


def _quarto_plan(
    project_type: str,
    render_dirs: dict[str, str] | None = None,
    quarto_settings: dict[str, Any] | None = None,
    directories: dict[str, str] | None = None,
) -> list[tuple[str, str]]:
    """The Quarto files the settings call for, as (path from the root, text)."""
    pairs = _render_pairs(render_dirs, directories)
    output_dir = _shared_output_dir(pairs)
    root_format = "revealjs" if project_type == "presentation" else "html"
    files = [
        (
            "_quarto.yml",
            quarto_yml(quarto_settings, root_format, project_root=True, output_dir=output_dir),
        )
    ]
    for key, source, target, parent in pairs:
        format = render_format(key, project_type)
        if parent != (output_dir or "."):
            # Outside the shared output folder: its own Quarto project, since
            # output-dir is a project setting
            relative = posixpath.relpath(target, source)
            files.append(
                (f"{source}/_quarto.yml", quarto_yml(quarto_settings, format, output_dir=relative))
            )
        elif format != root_format:
            files.append((f"{source}/_metadata.yml", quarto_yml(quarto_settings, format)))
    return files


def quarto_generate_all(
    project_path: str | Path,
    project_type: str,
    render_dirs: dict[str, str] | None = None,
    quarto_settings: dict[str, Any] | None = None,
    directories: dict[str, str] | None = None,
) -> list[Path]:
    """Write the project's Quarto configuration, as the R package does. Returns the files written.

    One root ``_quarto.yml`` holds the shared settings. Its ``output-dir`` is
    the folder most render targets share, and Quarto keeps each file's folder
    under it, so ``notebooks/x.ipynb`` renders to ``outputs/notebooks/x.html``.
    A folder whose format differs from the root's, such as a course's
    ``slides/``, gets a ``_metadata.yml`` with only its format, which inherits
    the rest from the root. A render target outside the shared folder keeps
    its own ``_quarto.yml`` with a relative ``output-dir``. Existing files are
    overwritten.

    Args:
        project_path: The project's root folder.
        project_type: The project type. "presentation" renders the root as revealjs. Any other
            type renders it as HTML.
        render_dirs: Maps a directory key to the folder its output goes to, relative to the
            project root. Keys with an empty target are skipped. Keys containing "slide" or
            "slides" render as revealjs. Default: no render folders.
        quarto_settings: Format options under ``html`` and ``revealjs`` keys, such as
            ``{"html": {"toc": False}}``. They override Framework's defaults, and only options
            that have a default are written.
        directories: Maps a directory key to its source folder, relative to the project root.
            A key missing here uses the key itself as the folder name. Missing folders are
            created.

    Returns:
        The files written, the root file first.

    Raises:
        FrameworkError: When ``project_path`` is not an existing folder.
    """
    root = Path(project_path).expanduser()
    if not root.is_dir():
        raise FrameworkError(f"Project path does not exist: {root}")
    for _, source, _, _ in _render_pairs(render_dirs, directories):
        (root / source).mkdir(parents=True, exist_ok=True)
    written = []
    for relative, text in _quarto_plan(project_type, render_dirs, quarto_settings, directories):
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        written.append(path)
    return written


@dataclass
class QuartoChanges:
    """What regenerating changes: ``write`` (path -> new text), ``unchanged``, ``kept``
    (per-folder files left in place), and ``remove``."""

    write: dict[str, str] = field(default_factory=dict)
    unchanged: list[str] = field(default_factory=list)
    kept: list[str] = field(default_factory=list)
    remove: list[str] = field(default_factory=list)


def quarto_changes(
    root: Path,
    project_type: str,
    render_dirs: dict[str, str] | None,
    quarto_settings: dict[str, Any] | None,
    directories: dict[str, str] | None,
    *,
    overwrite: bool = False,
    remove_legacy: bool = False,
    read: Any = None,
) -> QuartoChanges:
    """What ``quarto_regenerate()`` would change. Without ``overwrite``, an existing file
    only gains missing keys (``_add_missing_keys()``). ``read(path)`` returns a file's
    text as planned, or None; by default the file on disk."""

    def on_disk(relative: str) -> str | None:
        path = root / relative
        return path.read_text(encoding="utf-8") if path.is_file() else None

    read = read or on_disk
    plan = _quarto_plan(project_type, render_dirs, quarto_settings, directories)
    planned = {relative for relative, _ in plan}
    # Projects made before one root config have a _quarto.yml in each render folder,
    # each a separate Quarto project that ignores the root
    legacy: list[str] = []
    for key in render_dirs or {}:
        source = (directories or {}).get(key, key)
        if not isinstance(source, str) or not source or source == ".":
            continue
        for name in ("_quarto.yml", "_metadata.yml"):
            relative = f"{source}/{name}"
            if read(relative) is not None and relative not in planned:
                legacy.append(relative)
    # While those stay, the existing files keep the old layout as it is: an output-dir
    # added to the root would move where root documents render
    keep_layout = bool(legacy) and not remove_legacy
    changes = QuartoChanges()
    for relative, text in plan:
        current = read(relative)
        if current is None:
            changes.write[relative] = text
            continue
        if overwrite:
            new = text
        elif keep_layout:
            new = current
        else:
            new = _add_missing_keys(current, text)
        if new == current:
            changes.unchanged.append(relative)
        else:
            changes.write[relative] = new
    if remove_legacy:
        changes.remove = legacy
    else:
        changes.kept = legacy
    return changes


def _add_missing_keys(current: str, generated: str) -> str:
    """A Quarto file's text with the keys Framework needs and it lacks added: ``project:``,
    ``project: type:`` and ``output-dir:`` (at the root), and ``format:`` when it has
    none. Other keys, values, and comments stay as they are. A file that isn't valid YAML
    is left alone."""
    from framework import _yaml

    try:
        have = _yaml.load(current)
    except Exception:
        return current
    want = _yaml.load(generated) or {}
    if have is None:
        if any(line.split("#", 1)[0].strip() for line in current.splitlines()):
            return current
        have = {}
    if not isinstance(have, dict):
        return current
    lines = current.splitlines()

    def append_block(key: str) -> None:
        block = _yaml.dump({key: want[key]}).rstrip("\n").splitlines()
        if lines and lines[-1].strip():
            lines.append("")
        lines.extend(block)

    project = want.get("project")
    if isinstance(project, dict):
        if have.get("project") is None:
            append_block("project")
        elif isinstance(have["project"], dict):
            missing = [k for k in project if k not in have["project"]]
            at = next(
                (i for i, line in enumerate(lines) if re.match(r"^project:\s*(#.*)?$", line)),
                None,
            )
            if missing and at is not None:
                child = next((line for line in lines[at + 1 :] if re.match(r"^\s+\S", line)), None)
                indent = re.match(r"^(\s+)", child).group(1) if child else "  "  # type: ignore[union-attr]
                added = [f"{indent}{k}: {project[k]}" for k in missing]
                lines[at + 1 : at + 1] = added
    if have.get("format") is None and want.get("format") is not None:
        append_block("format")
    return "\n".join(lines) + ("\n" if lines else "")


@dataclass
class RegenerateResult:
    """What ``quarto_regenerate()`` did.

    Attributes:
        regenerated: The files written (or, in a dry run, that would be).
        backed_up: The files copied before they changed, as paths from the root.
        backup_location: The backup folder, or None.
        unchanged: Files already as Framework needs them.
        kept: Per-folder Quarto files from older projects, left in place.
        removed: Per-folder files removed (``overwrite`` with backups).
    """

    regenerated: list[Path]
    backed_up: list[str] = field(default_factory=list)
    backup_location: Path | None = None
    unchanged: list[str] = field(default_factory=list)
    kept: list[str] = field(default_factory=list)
    removed: list[str] = field(default_factory=list)


def quarto_regenerate(
    project_path: str | Path,
    backup: bool = True,
    overwrite: bool = False,
    dry_run: bool = False,
) -> RegenerateResult:
    """Bring a project's Quarto files in line with its settings.

    The files are one root ``_quarto.yml``, plus a ``_metadata.yml`` or
    ``_quarto.yml`` for render folders that need their own format or output
    folder (see ``quarto_generate_all()``), from ``project_type``,
    ``render_dirs``, ``quarto``, and ``directories`` in the settings.

    By default it never replaces your Quarto configuration. It creates the
    files that are missing and, in a file that exists, at most adds the keys
    Framework needs that it lacks (``project:``, ``project: type:`` and
    ``output-dir:``, and ``format:`` when there is none), keeping every other
    key, value, and comment. Per-folder ``_quarto.yml`` files from older
    projects are left in place and listed; while they stay, existing files
    are not changed at all.

    With ``overwrite=True`` it replaces the files with freshly generated ones
    (your theme, ``execute:``, and other custom keys are lost) and, with
    backups on, removes the per-folder files that the root configuration
    replaces. With ``backup=False`` it never removes a file.

    Args:
        project_path: The project's root folder, which must hold settings.yml or a
            Framework config.yml.
        backup: Copy each file before it is changed or removed, to
            ``.framework/backups/<timestamp>/``, which git ignores.
        overwrite: Replace existing Quarto files instead of adding missing keys.
        dry_run: Report what would change and change nothing.

    Returns:
        The files written, unchanged, kept, and removed, and the backups.

    Raises:
        FrameworkError: When the project has no settings file, or its settings turn the Quarto
            tool off.
    """
    from framework._backups import backup_dir, backup_files
    from framework.project import _settings_in

    root = Path(project_path).expanduser()
    settings_file = _settings_in(root)
    if settings_file is None:
        raise FrameworkError("Project settings.yml/config.yml not found")
    config = settings_read(settings_file)
    # A project without a tools section predates it and keeps Quarto
    tools = config.get("tools")
    if isinstance(tools, dict) and tools.get("quarto") is not True:
        raise FrameworkError(
            "This project doesn't use Quarto (tools: quarto is off in settings.yml). Set "
            "tools: {quarto: true} to turn it on, then run quarto_regenerate() again."
        )
    quarto = config.get("quarto") if isinstance(config.get("quarto"), dict) else None
    directories = config.get("directories") if isinstance(config.get("directories"), dict) else {}
    render_dirs = config.get("render_dirs") if isinstance(config.get("render_dirs"), dict) else {}
    changes = quarto_changes(
        root,
        str(config.get("project_type") or "project"),
        render_dirs,
        quarto,
        directories,
        overwrite=overwrite,
        remove_legacy=overwrite and backup,
    )
    for path in changes.kept:
        inform(
            f"Kept {path}: it makes {posixpath.dirname(path)}/ a separate Quarto project. "
            "quarto_regenerate(overwrite=True) folds it into the root _quarto.yml (backed up "
            "first)."
        )
    written = list(changes.write)
    if dry_run:
        for path in written:
            inform(f"Would write {path}")
        for path in changes.remove:
            inform(f"Would remove {path}")
        return RegenerateResult(
            [root / p for p in written],
            unchanged=changes.unchanged,
            kept=changes.kept,
            removed=changes.remove,
        )

    touched = [p for p in written if (root / p).is_file()] + changes.remove
    backed_up: list[str] = []
    location = None
    if backup and touched:
        relative = backup_dir(root)
        backed_up = backup_files(root, touched, relative)
        location = root / relative if backed_up else None
    for path in changes.remove:
        (root / path).unlink(missing_ok=True)
    for _, source, _, _ in _render_pairs(render_dirs, directories):
        (root / source).mkdir(parents=True, exist_ok=True)
    for path, text in changes.write.items():
        target = root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
    return RegenerateResult(
        [root / p for p in written],
        backed_up,
        location,
        unchanged=changes.unchanged,
        kept=changes.kept,
        removed=changes.remove,
    )
