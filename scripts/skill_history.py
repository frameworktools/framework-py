"""Record the bundle hash of every version of each built-in skill framework-py has
shipped, per variant (skills lock v2).

Pull, ``ai_skills_update()``, and ``upgrade()`` use the record as the package's
known hashes: a copy holding one of them, installed before
``.framework/skills.lock.json`` existed, is an unedited older version and is
updated rather than kept as locally edited. Every shipped built-in is SKILL.md
only (``.framework-skill.json`` is left out of the hash), so each version's
bundle hash is computed from its SKILL.md. The format is R's
``inst/templates/skill-history.json``:
``{"schema": 2, "skills": {"framework-data": {"python": ["..."]}}}``. Run it
after changing a skill, before release:

    uv run python scripts/skill_history.py           # write the record
    uv run python scripts/skill_history.py --check   # the record is current
"""

from __future__ import annotations

import argparse
import base64
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VARIANT = "python"
SKILLS = ROOT / "src" / "framework" / "templates" / "skills"
RECORD = ROOT / "src" / "framework" / "templates" / "skill-history.json"


def _git(*args: str) -> subprocess.CompletedProcess[bytes]:
    return subprocess.run(["git", "-C", str(ROOT), *args], capture_output=True, check=False)


def bundle(raw: bytes) -> str:
    """The bundle hash of a skill whose only file is this SKILL.md."""
    from framework.skill_sync import bundle_hash

    content = base64.b64encode(raw).decode("ascii")
    return bundle_hash([{"path": "SKILL.md", "content": content, "executable": False}])


def history() -> dict[str, dict[str, list[str]]]:
    skills: dict[str, dict[str, list[str]]] = {}
    for folder in sorted(p for p in SKILLS.iterdir() if p.is_dir()):
        path = (folder / "SKILL.md").relative_to(ROOT).as_posix()
        hashes = {bundle((folder / "SKILL.md").read_bytes())}
        commits = _git("log", "--format=%H", "--", path).stdout.decode().split()
        for commit in commits:
            shown = _git("show", f"{commit}:{path}")
            if shown.returncode == 0:
                hashes.add(bundle(shown.stdout))
        skills[folder.name] = {VARIANT: sorted(hashes)}
    return skills


def record() -> str:
    data = {
        "description": (
            "Bundle hash of every version of each built-in skill framework-py has shipped, "
            "per variant. Generated by scripts/skill_history.py."
        ),
        "schema": 2,
        "skills": history(),
    }
    return json.dumps(data, indent=2) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the record is stale")
    args = parser.parse_args()
    text = record()
    if args.check:
        current = RECORD.read_text(encoding="utf-8") if RECORD.exists() else ""
        # A record may list more versions than this checkout's history has (a shallow
        # clone), but never miss the current files
        data = json.loads(current or "{}")
        shipped = data.get("skills", {}) if data.get("schema") == 2 else {}
        for name, variants in json.loads(text)["skills"].items():
            now = bundle((SKILLS / name / "SKILL.md").read_bytes())
            have = set((shipped.get(name) or {}).get(VARIANT) or [])
            if now not in have or not have >= set(variants[VARIANT]):
                print(f"{RECORD.name} is stale for {name}: run scripts/skill_history.py")
                return 1
        print(f"{RECORD.name} is current")
        return 0
    RECORD.write_text(text, encoding="utf-8")
    print(f"Wrote {RECORD.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
