"""Record the SHA-256 of every SKILL.md framework-py has shipped, per skill.

``ai_skills_update()`` and ``upgrade()`` use the record to recognize an
unedited skill installed by an older release (before
``.framework/skills.lock.json`` existed) and update it rather than keep it as
locally edited. The format is R's ``inst/templates/skill-history.json``. Run
it after changing a skill, before release:

    uv run python scripts/skill_history.py           # write the record
    uv run python scripts/skill_history.py --check   # the record is current
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILLS = ROOT / "src" / "framework" / "templates" / "skills"
RECORD = ROOT / "src" / "framework" / "templates" / "skill-history.json"


def _git(*args: str) -> subprocess.CompletedProcess[bytes]:
    return subprocess.run(["git", "-C", str(ROOT), *args], capture_output=True, check=False)


def history() -> dict[str, list[str]]:
    skills: dict[str, list[str]] = {}
    for folder in sorted(p for p in SKILLS.iterdir() if p.is_dir()):
        path = (folder / "SKILL.md").relative_to(ROOT).as_posix()
        hashes = {hashlib.sha256((folder / "SKILL.md").read_bytes()).hexdigest()}
        commits = _git("log", "--format=%H", "--", path).stdout.decode().split()
        for commit in commits:
            shown = _git("show", f"{commit}:{path}")
            if shown.returncode == 0:
                hashes.add(hashlib.sha256(shown.stdout).hexdigest())
        skills[folder.name] = sorted(hashes)
    return skills


def record() -> str:
    data = {
        "description": (
            "SHA-256 of every SKILL.md framework-py has shipped, per skill. Generated by "
            "scripts/skill_history.py."
        ),
        "skills": history(),
    }
    return json.dumps(data, indent=2) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the record is stale")
    args = parser.parse_args()
    text = record()
    if args.check:
        current = RECORD.read_text(encoding="utf-8") if RECORD.exists() else ""
        # A record may list more versions than this checkout's history has (a shallow
        # clone), but never miss the current files
        shipped = json.loads(current or "{}").get("skills", {})
        for name, hashes in json.loads(text)["skills"].items():
            now = hashlib.sha256((SKILLS / name / "SKILL.md").read_bytes()).hexdigest()
            if now not in shipped.get(name, []) or not set(shipped[name]) >= set(hashes):
                print(f"{RECORD.name} is stale for {name}: run scripts/skill_history.py")
                return 1
        print(f"{RECORD.name} is current")
        return 0
    RECORD.write_text(text, encoding="utf-8")
    print(f"Wrote {RECORD.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
